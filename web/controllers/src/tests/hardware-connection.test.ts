import { flushPromises, mount } from '@vue/test-utils'
import { afterEach, expect, it, vi } from 'vitest'
import HardwareConnection from '../components/HardwareConnection.vue'
import { generateTemplate } from '../elixir/templates'
afterEach(() => { vi.unstubAllGlobals() })
it('connects on demand, captures selected input, handles disconnect, and never sends', async () => {
  const input = Object.assign(new EventTarget(), { id: 'in', name: 'Launch Control XL 3', manufacturer: 'Novation', type: 'input', state: 'connected', close: vi.fn(async () => input) })
  const output = Object.assign(new EventTarget(), { id: 'out', name: 'Launch Control XL 3', manufacturer: 'Novation', type: 'output', state: 'connected', send: vi.fn() })
  const access = Object.assign(new EventTarget(), { sysexEnabled: true, inputs: new Map([['in', input]]), outputs: new Map([['out', output]]) })
  const requestMIDIAccess = vi.fn(async () => access)
  vi.stubGlobal('isSecureContext', true); vi.stubGlobal('navigator', { requestMIDIAccess })
  const w = mount(HardwareConnection, { props: { template: generateTemplate('mixer') } })
  expect(requestMIDIAccess).not.toHaveBeenCalled()
  expect(w.findAll('button').at(-1)!.attributes('disabled')).toBeDefined()
  await w.find('button').trigger('click'); await flushPromises()
  expect(requestMIDIAccess).toHaveBeenCalledExactlyOnceWith({ sysex: true })
  expect(w.findAll('.port-selectors option')).toHaveLength(4)
  await w.find('.port-selectors select').setValue('in')
  await w.find('details input[type=checkbox]').setValue(true)
  await w.find('details button').trigger('click')
  for (let i = 0; i < 600; i++) input.dispatchEvent(Object.assign(new Event('midimessage'), { data: Uint8Array.of(0xf8) }))
  input.dispatchEvent(Object.assign(new Event('midimessage'), { data: Uint8Array.of(0xbe, 8, 64) }))
  await flushPromises()
  expect(w.find('pre').text()).toContain('be 08 40')
  input.state = 'disconnected'; access.inputs.clear(); access.dispatchEvent(new Event('statechange'))
  await flushPromises()
  expect(w.find('[role=alert]').text()).toContain('input disconnected')
  expect(w.text()).toContain('1 captured messages')
  expect(w.find('details button').attributes('disabled')).toBeDefined()
  expect(output.send).not.toHaveBeenCalled()
  await w.find('.slot-field input').setValue('16')
  expect(w.text()).toContain('Choose a custom-mode slot from 1 to 15')
  w.unmount()
})
it('keeps file preparation available after MIDI permission is denied', async () => {
  vi.stubGlobal('isSecureContext', true)
  vi.stubGlobal('navigator', { requestMIDIAccess: vi.fn(async () => { throw new Error('Permission denied') }) })
  const w = mount(HardwareConnection, { props: { template: generateTemplate('effects') } })
  await w.find('button').trigger('click'); await flushPromises()
  expect(w.find('[role=alert]').text()).toContain('Permission denied')
  expect(w.text()).toContain('File validated: Elixir Effects')
  expect(w.findAll('button').at(-1)!.attributes('disabled')).toBeDefined()
  w.unmount()
})
it('verifies identity and offers a backup without any hardware write', async () => {
  const { readFileSync } = await import('node:fs')
  const load = (path: string) => new Uint8Array(readFileSync(`${process.cwd()}/research/hardware/${path}`))
  const input = Object.assign(new EventTarget(), { id: 'in', name: 'LCXL3 1 MIDI In', manufacturer: 'Novation', type: 'input', state: 'connected', close: vi.fn(async () => input) })
  const output = Object.assign(new EventTarget(), { id: 'out', name: 'LCXL3 1 MIDI Out', manufacturer: 'Novation', type: 'output', state: 'connected', send: vi.fn((bytes: Uint8Array) => {
    const reply = bytes[1] === 126 ? load('slot1-reconnect/frame-001.syx') : load(`slot1-reconnect/frame-${bytes[9] === 0 ? '002' : '003'}.syx`)
    input.dispatchEvent(Object.assign(new Event('midimessage'), { data: reply }))
  }) })
  const access = Object.assign(new EventTarget(), { sysexEnabled: true, inputs: new Map([['in', input]]), outputs: new Map([['out', output]]) })
  vi.stubGlobal('isSecureContext', true); vi.stubGlobal('navigator', { requestMIDIAccess: vi.fn(async () => access) })
  const w = mount(HardwareConnection, { props: { template: generateTemplate('mixer') } })
  await w.find('button').trigger('click'); await flushPromises()
  await w.findAll('.port-selectors select')[0]!.setValue('in')
  await w.findAll('.port-selectors select')[1]!.setValue('out')
  const verify = w.findAll('button').find(b => b.text() === 'Verify device & back up slot 1')!
  await verify.trigger('click'); await flushPromises()
  expect(w.text()).toContain('firmware build 1563')
  expect(w.text()).toContain('No write performed.')
  const backup = w.findAll('button').find(b => b.text() === 'Download slot 1 backup')!
  expect(backup.attributes('disabled')).toBeUndefined()
  expect(output.send.mock.calls.map(([bytes]) => bytes[8] ?? null)).toEqual([null, 64, 64])
  expect(w.findAll('button').at(-1)!.attributes('disabled')).toBeDefined()
  const next = generateTemplate('effects'); await w.setProps({ template: next })
  expect(backup.attributes('disabled')).toBeDefined()
  w.unmount()
})
