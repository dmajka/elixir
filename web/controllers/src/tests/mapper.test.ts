import { flushPromises, mount } from '@vue/test-utils'
import { afterEach, expect, it, vi } from 'vitest'
import MidiMapper from '../components/AdminMidiMapper.vue'
import { generateTemplate } from '../elixir/templates'
import { decodeFile } from '../devices/novation/launch-control-xl3/codec'
const wrappers: ReturnType<typeof mount>[] = []
afterEach(() => { wrappers.forEach(w => w.unmount()); wrappers.length = 0; vi.restoreAllMocks() })
function setup() { const w = mount(MidiMapper); wrappers.push(w); return w }
it('loads complete presets and shows resolved program triggers', async () => {
  const w = setup()
  expect(w.findAll('.control')).toHaveLength(48)
  expect(w.text()).toContain('48/48 assigned')
  await w.findAll('.setup select')[1]!.setValue('sequencer')
  await w.findAll('.control').at(-1)!.trigger('click')
  expect(w.find('.editor').text()).toContain('program-change 3 · channel 16')
  expect(w.text()).toContain('Mapping is valid.')
})
it('searches, applies, rejects incompatible behavior and removes assignments', async () => {
  const w = setup()
  await w.find('.parameter-browser input').setValue('master filter')
  expect(w.findAll('.parameter-results button')).toHaveLength(1)
  await w.find('.parameter-results button').trigger('click')
  await w.find('.editor form').trigger('submit')
  expect(w.find('.editor').text()).toContain('Master filter · cc 12 · channel 16')
  await w.findAll('.control')[32]!.trigger('click')
  const behavior = w.findAll('.editor form select')[1]!
  await behavior.setValue('toggle')
  await w.find('.editor form').trigger('submit')
  expect(w.find('[role=alert]').text()).toContain('momentary hardware')
  expect(w.findAll('.control')[32]!.text()).toContain('D1 Mute')
  await w.findAll('.editor form .actions button')[1]!.trigger('click')
  expect(w.text()).toContain('47/48 assigned')
  expect(w.text()).toContain('button.1.1')
})
it('validates channel edits and saves user mappings for the session', async () => {
  const w = setup()
  const channels = w.findAll('.setup input')
  await channels[1]!.setValue('0')
  expect(w.find('.export-panel button').attributes('disabled')).toBeDefined()
  await channels[1]!.setValue('14')
  await w.findAll('.export-panel button')[1]!.trigger('click')
  expect(w.findAll('.setup select')[1]!.findAll('option')).toHaveLength(6)
  await w.findAll('.setup select')[1]!.setValue('effects')
  await w.findAll('.setup select')[1]!.setValue('user:0')
  expect((w.findAll('.setup input')[1]!.element as HTMLInputElement).value).toBe('14')
})
it('downloads a decodable custom mode through the UI', async () => {
  const w = setup()
  let blob: Blob | undefined
  vi.stubGlobal('URL', { createObjectURL: vi.fn((b: Blob) => { blob = b; return 'blob:test' }), revokeObjectURL: vi.fn() })
  const click = vi.spyOn(HTMLAnchorElement.prototype, 'click').mockImplementation(() => {})
  await w.find('.export-panel button').trigger('click')
  await flushPromises()
  expect(click).toHaveBeenCalledOnce()
  const reader = new FileReader()
  const bytes = await new Promise<ArrayBuffer>((resolve, reject) => { reader.onload = () => resolve(reader.result as ArrayBuffer); reader.onerror = reject; reader.readAsArrayBuffer(blob!) })
  const mode = decodeFile(new Uint8Array(bytes))
  expect(mode.destination).toBe(127)
  expect(mode.mode.controls.filter(c => c.type !== 'off')).toHaveLength(48)
  vi.unstubAllGlobals()
})
it('creates a blank user mapping, configures range and channel, then applies it', async () => {
  const w = setup()
  await w.findAll('.export-panel button')[2]!.trigger('click')
  expect(w.text()).toContain('0/48 assigned')
  await w.find('.parameter-browser input').setValue('master filter')
  await w.find('.parameter-results button').trigger('click')
  const fields = w.findAll('.editor form input')
  await fields[1]!.setValue('My filter')
  await fields[2]!.setValue('13')
  await w.find('input[type=checkbox]').setValue(true)
  const numbers = w.findAll('.editor fieldset input[type=number]')
  await numbers[0]!.setValue('20'); await numbers[1]!.setValue('100')
  await w.find('.editor form').trigger('submit')
  expect(w.text()).toContain('1/48 assigned')
  expect(w.find('.editor').text()).toContain('Master filter · cc 12 · channel 13')
  expect(w.find('.control').text()).toContain('My filter')
  await w.find('input[type=checkbox]').setValue(true)
  await w.findAll('.editor fieldset input[type=number]')[0]!.setValue('110')
  await w.find('.editor form').trigger('submit')
  expect(w.find('[role=alert]').text()).toContain('minimum exceeds maximum')
  expect(w.find('.control').text()).toContain('My filter')
})
it('rejects invalid JSON imports without replacing the workspace', async () => {
  const w = setup(), input = w.find('input[type=file]')
  Object.defineProperty(input.element, 'files', { configurable: true, value: [{ size: 10, text: async () => '{"invalid":true}' }] })
  await input.trigger('change'); await flushPromises()
  expect(w.find('[role=alert]').exists()).toBe(true)
  expect(w.text()).toContain('48/48 assigned')
})

it('imports a saved user template and exposes its assignments', async () => {
  const w = setup(), input = w.find('input[type=file]')
  const saved = generateTemplate('effects', { remoteTracks: 14, remoteGlobal: 13 })
  saved.name = 'Saved Effects'
  Object.defineProperty(input.element, 'files', { configurable: true, value: [{ size: 1000, text: async () => JSON.stringify(saved) }] })
  await input.trigger('change'); await flushPromises()
  expect(w.find('[role=alert]').exists()).toBe(false)
  expect(w.find('.editor').text()).toContain('Delay Time / Grain position · cc 96 · channel 13')
  expect(w.findAll('.setup select')[1]!.findAll('option').at(-1)!.text()).toBe('Saved Effects (user)')
})
it('drags a track family onto column one and rejects incompatible drops atomically', async () => {
  const w = setup()
  const dataTransfer = { getData: () => 'tracks.d1.fx-send' }
  await w.find('.control').trigger('drop', { dataTransfer })
  expect(w.findAll('.control')[6]!.text()).toContain('OH FX send')
  expect(w.findAll('.control')[7]!.text()).toContain('Master volume')
  expect(w.find('.editor').text()).toContain('D1 FX send · cc 64 · channel 15')
  await w.findAll('.control')[32]!.trigger('drop', { dataTransfer })
  expect(w.find('[role=alert]').text()).toContain('continuous')
  expect(w.findAll('.control')[32]!.text()).toContain('D1 Mute')
  await w.find('.led-swatches button[aria-label="LED color: Orange"]').trigger('click')
  await w.find('.editor form').trigger('submit')
  expect(w.find('.control').attributes('style')).toContain('#f5ad66')
})
it('distinguishes track/global scopes and knob/pad types without changing channels', async () => {
  const w = setup()
  await w.findAll('.parameter-modes button')[1]!.trigger('click')
  await w.find('.parameter-browser input').setValue('fx send')
  expect(w.findAll('.parameter-results button')).toHaveLength(1)
  expect(w.find('.parameter-results button').text()).toContain('FX send')
  expect(w.find('.parameter-results button').text()).toContain('ch 15')
  await w.findAll('.parameter-modes button')[2]!.trigger('click')
  await w.find('.parameter-browser input').setValue('master filter')
  expect(w.find('.parameter-results button').text()).toContain('ch 16')
  await w.findAll('.parameter-browser select')[0]!.setValue('button')
  expect(w.findAll('.parameter-results button')).toHaveLength(0)
})
