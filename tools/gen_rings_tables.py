# Kettle: the lookup tables of the Rings port (firmware/src/rings.c) into firmware/src/rings_tables.h.
#
#   tools/gen_rings_tables.py [OUT]
#
# The formulas are Mutable Instruments Rings' (rings/resources/lookup_tables.py, Copyright 2015 Emilie Gillet, MIT
# licence), in fixed point: the stiffness curve of the modal resonator's partials, the SVF's delay at the string's
# damping cutoff, the FM voice's quantized frequency ratios and its sine. The output is committed; run this again only if
# the port's formats change.
import math
import sys
from pathlib import Path


def arr(name, ctype, vals, per=12):
    out = [f"static const {ctype} {name}[{len(vals)}] = {{"]
    for i in range(0, len(vals), per):
        out.append("    " + ", ".join(str(int(v)) for v in vals[i:i + per]) + ",")
    out.append("};")
    return out


def main():
    out_path = Path(sys.argv[1] if len(sys.argv) > 1 else Path(__file__).parent.parent / "firmware/src/rings_tables.h")
    lines = ["/* SPDX-License-Identifier: GPL-3.0-only",
             " * Kettle: the Rings port's tables (rings.c), from Mutable Instruments Rings' lookup_tables.py (Copyright",
             " * 2015 Emilie Gillet, MIT licence). Generated by tools/gen_rings_tables.py; do not edit. */",
             "#pragma once", "#include <stdint.h>", ""]

    # the partials' stiffness against STRUCTURE (257 steps), Q24
    stiff = []
    for i in range(257):
        g = i / 256.0
        if g < 0.25:
            s = -(0.25 - g) * 0.25
        elif g < 0.3:
            s = 0.0
        elif g < 0.9:
            s = 0.01 * 10 ** ((g - 0.3) / 0.6 * 2.005) - 0.01
        else:
            h = ((g - 0.9) / 0.1) ** 2
            s = 1.5 - math.cos(h * math.pi) / 2.0
        stiff.append(s)
    stiff[-1] = stiff[-2] = 2.0
    lines += ["/* the modal resonator's stiffness against STRUCTURE / 256, Q24 */"]
    lines += arr("RG_STIFF", "int32_t", [round(s * 16777216) for s in stiff], 8)
    lines.append("")

    # the SVF's phase delay at a cutoff `n` semitones above the pitch, a fraction of the period, Q16
    shift = [2.0 * math.atan(1.0 / 2.0 ** (n / 12.0)) / (2.0 * math.pi) for n in range(257)]
    lines += ["/* the string's damping filter's delay, in periods, at a cutoff n semitones above its pitch, Q16 */"]
    lines += arr("RG_SVF_SHIFT", "uint16_t", [round(s * 65536) for s in shift])
    lines.append("")

    # the FM voice's modulator ratios (semitones), quantized, against STRUCTURE / 64
    ratios = [0.5, 0.5 * 2 ** (16 / 1200.0), math.sqrt(2) / 2, math.pi / 4, 1.0, 1.0 * 2 ** (16 / 1200.0),
              math.sqrt(2), math.pi / 2, 7.0 / 4, 2, 2 * 2 ** (16 / 1200.0), 9.0 / 4, 11.0 / 4, 2 * math.sqrt(2), 3,
              math.pi, math.sqrt(3) * 2, 4, math.sqrt(2) * 3, math.pi * 3 / 2, 5, math.sqrt(2) * 4, 8]
    scale = []
    for r in ratios:
        st = 12 * math.log2(r)
        scale += [st, st, st]
    target = int(2 ** math.ceil(math.log2(len(scale))))
    while len(scale) < target:
        diffs = [scale[i + 1] - scale[i] for i in range(len(scale) - 1)]
        gap = diffs.index(max(diffs))
        scale = scale[:gap + 1] + [(scale[gap] + scale[gap + 1]) / 2] + scale[gap + 1:]
    scale.append(scale[-1])
    lines += ["/* the FM voice's modulator ratio, semitones, against STRUCTURE / 128 (quantized: flat stretches), Q16 */"]
    lines += arr("RG_FM_RATIO", "int32_t", [round(s * 65536) for s in scale])
    lines.append("")
    # sin(2 pi i / 4096), 4096 points and the wrap one, Q15 (Rings' lut_sine; the LXR's table is a little off)
    lines += ["/* sin(2 pi i / 4096) and the wrap point, x 32767 (the FM voice's; LXR_SINE is not quite a sine) */"]
    lines += arr("RG_SINE", "int16_t", [round(math.sin(2 * math.pi * i / 4096) * 32767) for i in range(4097)], 16)
    lines.append("")
    out_path.write_text("\n".join(lines))


if __name__ == "__main__":
    main()
