"""Elixir: the fixed-point tables of the sound engine (the FM-1 has no FPU).

  tools/gen_tables.py OUT.h

Each table is a curve the LXR firmware computes in float at run time (Core/Src/Soundengine/...), sampled here so the
engine needs no float. The formulas are copied from the LXR sources named in each comment; the engine interpolates
between points where the input is continuous (a modulated parameter: 0..1 as Q16).
"""
import math
import sys

FS = 44100                    # the FM-1's I2S runs at 44.1176 kHz; the tables use the nominal rate
BLOCK = 64                    # LXR OUTPUT_DMA_SIZE with USE_BIG_SAMPLE_BUFFER: envelopes and LFOs step once a block
LFO_SR = FS / BLOCK


def arr(name, ctype, vals, per=12):
    out = [f"static const {ctype} {name}[{len(vals)}] = {{"]
    for i in range(0, len(vals), per):
        out.append("    " + ", ".join(str(int(v)) for v in vals[i:i + per]) + ",")
    out.append("};")
    return out


def clampi(v, lo, hi):
    return max(lo, min(hi, int(round(v))))


def shaper(val, shape):       # MIDI/valueShaper.h valueShaperF2F
    k = 2 * shape / (1.0001 - shape)
    return (1 + k) * val / (1 + k * abs(val))


def main(path):
    L = ["/* generated by tools/gen_tables.py: do not edit */", "#pragma once", "#include <stdint.h>",
         f"#define FS {FS}", f"#define BLOCK {BLOCK}", ""]

    # MidiNoteNumbers.h MidiNoteFrequencies -> Oscillator.c freq2PhaseIncr: inc = f * 2^32 / FS
    L += ["/* the phase increment of MIDI note n (8.18 Hz .. 12.5 kHz), 2^32 = one cycle a sample */"]
    L += arr("NOTE_INC", "uint32_t", [clampi(8.1757989156 * 2 ** (n / 12) * 2 ** 32 / FS, 0, 2 ** 32 - 1)
                                      for n in range(128)], 8)
    L += [f"#define INC_440 {int(440 * 2 ** 32 / FS)}u   /* freqToTableIndex's octave boundaries start here */"]

    # SlopeEg2.c slopeEg2_calcTime (USE_BIG_SAMPLE_BUFFER: x2, capped at 1): the per-block step, Q24
    def eg_time(d, amount):
        v = d / 127
        r = (1 - ((1 + amount) * v / (1 + amount * abs(v)))) * 2
        return min(1.0, r)
    katk = 2 * 0.99 / (1 - 0.99)
    kdec = 2 * 0.999 / (1 - 0.999)
    L += ["", "/* SlopeEg2 attack / decay and DecayEg decay: the value's step a block, Q24 (1.0 = 1 << 24) */"]
    L += arr("EG_ATK", "uint32_t", [clampi(eg_time(d, katk) * (1 << 24), 0, 1 << 24) for d in range(128)], 8)
    L += arr("EG_DEC", "uint32_t", [clampi(eg_time(d, kdec) * (1 << 24), 0, 1 << 24) for d in range(128)], 8)

    # SlopeEg2.c slopeEg2_setSlope; Decay.c DecayEg_setSlope (a clamped short of 1: the LXR divides by zero at 127)
    def k_of(a):
        return 2 * a / (1 - a)
    sl, isl, dsl = [], [], []
    for d in range(128):
        a = ((d / 127) - 0.5) * 1.999
        sl.append(clampi(k_of(a) * 65536, -2 ** 31, 2 ** 31 - 1))
        isl.append(clampi(k_of(-a) * 65536, -2 ** 31, 2 ** 31 - 1))
        a2 = min(0.9995, ((d / 127) - 0.5) * 2)
        dsl.append(clampi(k_of(a2) * 65536, -2 ** 31, 2 ** 31 - 1))
    L += ["", "/* the envelopes' slope k (out = (1 + k) v / (1 + k |v|)), Q16: amp EG decay, its attack, the pitch EG */"]
    L += arr("EG_SLOPE", "int32_t", sl, 8)
    L += arr("EG_ISLOPE", "int32_t", isl, 8)
    L += arr("DEC_SLOPE", "int32_t", dsl, 8)

    # MidiParser.c calcPitchModAmount: (d / 127)^2 * PITCH_AMOUNT_FACTOR (32), Q16
    L += ["", "/* the pitch EG's depth: (d / 127)^2 x 32, Q16 */"]
    L += arr("PITCH_AMT", "uint32_t", [round((d / 127) ** 2 * 32 * 65536) for d in range(128)], 8)

    # ResonantFilter.c SVF_directSetFilterValue (f = val * 0.45) after valueShaperF2F(v, FILTER_SHAPER -0.9),
    # g = fastTan(pi f) (the Pade form). 1025 points over v = 0..1, Q16
    def fast_tan(x):
        x2 = x * x
        return (-15 * x + x * x2) / (3 * (-5 + 2 * x2))
    ff, gg = [], []
    for i in range(1025):
        f = shaper(i / 1024, -0.9) * (0.5 * 0.90)
        ff.append(clampi(f * 65536, 0, 2 ** 31 - 1))
        gg.append(clampi(fast_tan(math.pi * f) * 65536, 0, 2 ** 31 - 1))
    L += ["", "/* the filter: f (cutoff / FS) and the integrator gain g = tan(pi f) of a 0..1 cutoff, Q16 */"]
    L += arr("FILT_F", "int32_t", ff, 10)
    L += arr("FILT_G", "int32_t", gg, 10)

    # ResonantFilter.c softClipTwo(x) = x * tanhXdX(0.5 x), tanhXdX the Pade form; over |x| < 32, step 1/32
    def tanhxdx(x):
        a = x * x
        return ((a + 105) * a + 945) / ((15 * a + 420) * a + 945)
    sc = [round(x * tanhxdx(0.5 * x) * 65536) for x in (i / 32 for i in range(1025))]
    L += ["", "/* softClipTwo(x) for x = i / 32 (0..32), Q16; odd */"]
    L += arr("SOFTCLIP", "int32_t", sc, 10)

    # ResonantFilter.c fastTanh: 4.15 x / (4.29 + x^2), +-1 beyond 1.95; x = i / 256 (0..2), Q16
    def ftanh(x):
        return 1.0 if x > 1.95 else 4.15 * x / (4.29 + x * x)
    L += ["", "/* fastTanh(x) for x = i / 256 (0..2), Q16; odd, 1 beyond */"]
    L += arr("FASTTANH", "int32_t", [round(ftanh(i / 256) * 65536) for i in range(513)], 10)

    # MidiParser.c VOICE_DECIMATION: valueShaperF2F(v, -0.7), the decimator's phase step (1 = every sample), Q16
    L += ["", "/* the sample rate reducer's step a sample (Q16, 1.0 = full rate) of a 0..1 setting */"]
    L += arr("DECIM", "uint32_t", [clampi(shaper(i / 1024, -0.7) * 65536, 0, 65536) for i in range(1025)], 10)

    # lfo.c lfo_setFreq: f = (1/128 + v (1 - 1/128))^3 * LFO_MAX_F (200 Hz); lfo_calcPhaseInc: f / LFO_SR * 2^32
    def lfo_inc(v):
        f = 0.0078125 + v * (1 - 0.0078125)
        return (f ** 3) * 200 / LFO_SR * 2 ** 32
    L += ["", "/* the LFO's free-running phase step a block, 2^32 = a cycle, of a 0..1 rate */"]
    L += arr("LFO_INC", "uint32_t", [clampi(lfo_inc(i / 1024), 1, 2 ** 32 - 1) for i in range(1025)], 8)

    # DrumVoice.c Drum_updatePan: sqrt((127 - p) / 127), sqrt(p / 127); Q15 (32768 = 1)
    L += ["", "/* constant power pan: the left and the right gain of pan 0..127, Q15 (32768 = 1) */"]
    L += arr("PAN_L", "uint16_t", [round(math.sqrt((127 - p) / 127) * 32768) for p in range(128)], 12)
    L += arr("PAN_R", "uint16_t", [round(math.sqrt(p / 127) * 32768) for p in range(128)], 12)

    # 2^(i/256), Q16, for the compressor's dB <-> gain (log2 domain)
    L += ["", "/* 2^(i / 256), Q16 (i = 0..256): exp2's mantissa; log2 is its inverse search */"]
    L += arr("EXP2_T", "uint32_t", [round(2 ** (i / 256) * 65536) for i in range(257)], 10)

    with open(path, "w") as f:
        f.write("\n".join(L) + "\n")


if __name__ == "__main__":
    main(sys.argv[1])
