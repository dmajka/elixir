# Kettle: Grids' drum map into firmware/src/grids_map.h.
#
#   tools/gen_grids.py GRIDS_RESOURCES_CC [OUT]
#
# GRIDS_RESOURCES_CC: grids/resources.cc of Emilie Gillet's Grids (https://github.com/pichenettes/eurorack, the AVR
# projects: GPL-3.0-or-later, used here under GPL-3.0). Its 25 nodes (3 parts x 32 steps of levels 0..255) and their
# places on the 5 x 5 map (pattern_generator.cc drum_map). The output is committed; run this again only to check it.
import re
import sys
from pathlib import Path

# pattern_generator.cc drum_map[x][y]: the node at each point of the map
DRUM_MAP = [[10, 8, 0, 9, 11], [15, 7, 13, 12, 6], [18, 14, 4, 5, 3], [23, 16, 21, 1, 2], [24, 19, 17, 20, 22]]


def main():
    src = Path(sys.argv[1]).read_text()
    out = Path(sys.argv[2]) if len(sys.argv) > 2 else Path(__file__).resolve().parents[1] / "firmware/src/grids_map.h"
    nodes = {}
    for m in re.finditer(r"node_(\d+)\[\] PROGMEM = \{(.*?)\};", src, re.S):
        nodes[int(m.group(1))] = [int(x) for x in re.findall(r"\d+", m.group(2))]
    assert sorted(nodes) == list(range(25)) and all(len(v) == 96 for v in nodes.values()), "25 nodes of 96"
    L = ["/* SPDX-License-Identifier: GPL-3.0-only",
         " * Copyright (C) 2011-2012 Emilie Gillet (Grids: grids/resources.cc, pattern_generator.cc; GPL-3.0-or-later,",
         " * here under GPL-3.0). Generated by tools/gen_grids.py; do not edit.",
         " * Grids' drum map: 25 nodes, each 3 parts (BD, SD, HH) x 32 steps (32nds of a bar) of levels 0..255, at the",
         " * points of a 5 x 5 map (GRIDS_AT[x][y]: a node's number). */",
         "#pragma once",
         "#include <stdint.h>",
         "",
         "static const uint8_t GRIDS_NODE[25][96] = {"]
    for n in range(25):
        v = nodes[n]
        L.append("    {" + ", ".join(str(x) for x in v[:24]) + ",")
        for k in range(24, 96, 24):
            L.append("     " + ", ".join(str(x) for x in v[k:k + 24]) + ("," if k + 24 < 96 else "},"))
    L.append("};")
    L.append("static const uint8_t GRIDS_AT[5][5] = {")
    for row in DRUM_MAP:
        L.append("    {" + ", ".join(str(x) for x in row) + "},")
    L.append("};")
    out.write_text("\n".join(L) + "\n")
    print(f"grids: {out}")


if __name__ == "__main__":
    main()
