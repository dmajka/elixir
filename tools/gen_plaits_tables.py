# Elixir: the lookup tables of the Plaits port (firmware/src/plaits.c) into firmware/src/plaits_tables.h.
#
#   EURORACK=path/to/eurorack tools/gen_plaits_tables.py [OUT]
#
# Mutable Instruments Plaits' tables (plaits/resources.cc and plaits/dsp/speech/lpc_speech_synth_words.cc, Copyright
# 2016-2023 Emilie Gillet, MIT licence), read from a checkout of github.com/pichenettes/eurorack and written in the
# port's fixed-point formats, plus the port's own exp2 and log2 tables. The output is committed; run this again only if
# the port's formats change.
import math
import os
import re
import sys
from pathlib import Path


def arr(name, ctype, vals, per=12):
    out = [f"static const {ctype} {name}[{len(vals)}] = {{"]
    for i in range(0, len(vals), per):
        out.append("    " + ", ".join(str(int(v)) for v in vals[i:i + per]) + ",")
    out.append("};")
    return out


def read_arrays(path):
    """name -> list of numbers, for every `const <type> name[] = { ... };` in a C++ file"""
    text = Path(path).read_text()
    text = re.sub(r"//[^\n]*", "", text)
    out = {}
    for m in re.finditer(r"const\s+\w+\s+(\w+)\[\]\s*=\s*\{(.*?)\};", text, re.S):
        vals = []
        if "{" in m.group(2):
            continue                                                    # (a table of structs)
        for tok in m.group(2).replace("\n", " ").split(","):
            tok = tok.strip()
            if not tok:
                continue
            vals.append(int(tok, 16) if tok.lower().startswith(("0x", "-0x")) else float(tok))
        out[m.group(1)] = vals
    return out


def q(vals, bits):
    return [round(v * (1 << bits)) for v in vals]


def main():
    root = Path(os.environ.get("EURORACK", "")) / "plaits"
    if not (root / "resources.cc").exists():
        sys.exit("set EURORACK to a checkout of github.com/pichenettes/eurorack")
    out_path = Path(sys.argv[1] if len(sys.argv) > 1 else Path(__file__).parent.parent / "firmware/src/plaits_tables.h")
    res = read_arrays(root / "resources.cc")
    words = read_arrays(root / "dsp/speech/lpc_speech_synth_words.cc")
    L = ["/* SPDX-License-Identifier: GPL-3.0-only",
         " * Elixir: the Plaits port's tables (plaits.c), from Mutable Instruments Plaits' resources (Copyright 2016-2023",
         " * Emilie Gillet, MIT licence). Generated by tools/gen_plaits_tables.py; do not edit. */",
         "#pragma once", "#include <stdint.h>", ""]

    L += ["/* 2^(i / 256), Q30 (and one past) */"]
    L += arr("PL_E2", "uint32_t", [round(2 ** (i / 256) * (1 << 30)) for i in range(257)], 8)
    L += ["/* log2(1 + i / 256), Q24 */"]
    L += arr("PL_L2", "int32_t", [round(math.log2(1 + i / 256) * (1 << 24)) for i in range(257)], 8)
    L += ["/* the modal resonator's stiffness against STRUCTURE x 64, Q24 */"]
    L += arr("PL_STIFF", "int32_t", q(res["lut_stiffness"], 24), 8)
    L += ["/* the string's damping filter's delay compensation against its cutoff (semitones), Q16 */"]
    L += arr("PL_SVF_SHIFT", "int32_t", q(res["lut_svf_shift"], 16), 8)
    L += ["/* the wavefolders (waveshaping), Q15 */"]
    L += arr("PL_FOLD", "int16_t", [max(-32768, min(32767, v)) for v in q(res["lut_fold"], 15)])
    L += arr("PL_FOLD2", "int16_t", [max(-32768, min(32767, v)) for v in q(res["lut_fold_2"], 15)])
    L += ["/* the waveshapers (waveshaping): Plaits' own int16 tables, inverse tan, inverse sin, linear, bump, double bump */"]
    ws = []
    for n in ("lut_ws_inverse_tan", "lut_ws_inverse_sin", "lut_ws_linear", "lut_ws_bump", "lut_ws_double_bump"):
        ws += [int(v) for v in res[n]]
    ws += [int(v) for v in res["lut_ws_double_bump"]]                  # (the sentinel: the last one again)
    L += arr("PL_WS", "int16_t", ws)
    L += ["/* the 2-op FM's ratio quantizer, semitones, Q16 */"]
    L += arr("PL_FM_Q", "int32_t", q(res["lut_fm_frequency_quantizer"], 16), 8)
    L += ["/* the LPC speech synthesizer's excitation pulse */"]
    L += arr("PL_LPC_PULSE", "int8_t", [int(v) for v in res["lut_lpc_excitation_pulse"]])
    L += ["/* the wavetables: 4 banks x 8 x 8 waves of 256 + 4 samples, integrated (Plaits' wav_integrated_waves) */"]
    L += arr("PL_WAVES", "int16_t", [int(v) for v in res["wav_integrated_waves"]], 16)
    L += ["/* the speech synthesizer's LPC word banks (TI ROMs' LPC10 words) */"]
    for i in range(5):
        L += arr(f"PL_BANK{i}", "uint8_t", [int(v) for v in words[f"bank_{i}"]], 16)
    out_path.write_text("\n".join(L) + "\n")
    print(f"{out_path}: {out_path.stat().st_size} bytes")


if __name__ == "__main__":
    main()
