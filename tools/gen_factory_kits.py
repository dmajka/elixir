# Elixir: the built-in bank of LXR-02 kits (firmware/src/kit.c): from 0.19, the LXR-02's factory kits in
# assets/kits/factory, distributed with Erica Synths' permission (assets/kits/README.md). tools/build.py, tools/gen.sh
# and web/emu/build.sh run it into build/gen/factory_kits.h.
#
#   tools/gen_factory_kits.py OUT_H DIR[:DIR ...] [DIR ...]
#
# Each DIR is searched (recursively) for NN-NAME.SND files: an LXR project folder (PROJ00 ...) or a folder of them.
# Kits come in the order given, by their numbers within a folder; Init/empty kits and repeats (the same bytes) are
# left out. A kit file is 8 name bytes and the LXR's 247 sound parameters (presetManager.c preset_saveDrumsetSD).
# 0.23-test5: packed for flash. Each parameter is stored as its value less the bank's lowest for it, in as many bits
# as the bank's spread needs (FK_LO, FK_W), the kits' bits one after another, low bits first (kit.c fk_value);
# the names apart (FACTORY_NAMES). 255 B a kit become ~174.
import re
import sys
from pathlib import Path

LXR_PARAMS = 247
INIT = re.compile(r"^(init|initk|initkit|empty|in\s*k)$", re.I)


def kits_in(d):
    files = []
    for f in Path(d).rglob("*"):
        m = re.match(r"^(\d+)-(.*)\.snd$", f.name, re.I)
        if m and f.is_file():
            files.append((str(f.parent), int(m.group(1)), f))
    for _, _, f in sorted(files, key=lambda t: (t[0], t[1])):
        b = f.read_bytes()
        if len(b) < 8 + 16 or len(b) > 8 + LXR_PARAMS + 64:
            continue
        name = bytes(c if 32 <= c < 127 else 32 for c in b[:8]).decode().strip()
        if INIT.match(name) or re.search(r"-(INITK|EMPTY|IN__K)\.SND$", f.name, re.I):
            continue
        data = b[8:8 + LXR_PARAMS].ljust(LXR_PARAMS, b"\0")
        yield (name or "Kit")[:8].ljust(8), data, f


def main():
    if len(sys.argv) < 3:
        sys.exit(__doc__ or "usage: gen_factory_kits.py OUT_H DIR [DIR ...]")
    out, seen, kits = Path(sys.argv[1]), set(), []
    for d in [d for a in sys.argv[2:] for d in a.split(":") if d]:   # (ELIXIR_KITS_DIR as it is: ':' between)
        if not Path(d).is_dir():
            sys.exit(f"gen_factory_kits: no folder {d}")
        for name, data, f in kits_in(d):
            if data in seen:
                continue
            seen.add(data)
            kits.append((name, data, f))
    if not kits:
        sys.exit("gen_factory_kits: no LXR kit files (NN-NAME.SND) found")
    if len(kits) > 250:
        kits = kits[:250]
    lo = [min(k[1][i] for k in kits) for i in range(LXR_PARAMS)]
    w = [(max(k[1][i] for k in kits) - lo[i]).bit_length() for i in range(LXR_PARAMS)]
    nbytes = (sum(w) + 7) // 8
    names, rows = [], []
    for name, data, f in kits:
        acc = nb = 0
        packed = bytearray()
        for i in range(LXR_PARAMS):
            acc |= (data[i] - lo[i]) << nb
            nb += w[i]
            while nb >= 8:
                packed.append(acc & 255)
                acc >>= 8
                nb -= 8
        if nb:
            packed.append(acc)
        assert len(packed) == nbytes
        c = name.strip().replace("*/", "")
        names.append("    {" + ", ".join(str(x) for x in name.encode()) + "},   /* " + c + " */")
        rows.append("    {" + ", ".join(str(x) for x in packed) + "},")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("/* generated by tools/gen_factory_kits.py: the LXR-02's factory kits (Erica Synths, by permission),\n"
                   " * packed: parameter i is FK_LO[i] + FK_W[i] bits of the kit's row, low bits first */\n"
                   f"#define FACTORY_NKITS {len(kits)}u\n#define FK_BYTES {nbytes}u\n"
                   f"static const uint8_t FK_LO[{LXR_PARAMS}] = {{{', '.join(map(str, lo))}}};\n"
                   f"static const uint8_t FK_W[{LXR_PARAMS}] = {{{', '.join(map(str, w))}}};\n"
                   "static const uint8_t FACTORY_NAMES[FACTORY_NKITS][8] = {\n" + "\n".join(names) + "\n};\n"
                   "static const uint8_t FACTORY_BITS[FACTORY_NKITS][FK_BYTES] = {\n" + "\n".join(rows) + "\n};\n")
    print(f"factory kits: {len(kits)}, {nbytes} B each packed ({', '.join(k[0].strip() for k in kits[:6])} ...) -> {out}")


if __name__ == "__main__":
    main()
