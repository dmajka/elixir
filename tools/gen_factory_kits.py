# Elixir: a built-in bank of LXR-02 kits from LOCAL .SND files, for a private build (firmware/src/kit.c,
# ELIXIR_FACTORY_KITS). The LXR-02's factory and Hrtl kits are not Elixir's to redistribute, so the output goes to
# build/gen (never committed) and web/make_site.py refuses to publish a build that has it.
#
#   tools/gen_factory_kits.py OUT_H DIR[:DIR ...] [DIR ...]
#
# Each DIR is searched (recursively) for NN-NAME.SND files: an LXR project folder (PROJ00 ...) or a folder of them.
# Kits come in the order given, by their numbers within a folder; Init/empty kits and repeats (the same bytes) are
# left out. A kit file is 8 name bytes and the LXR's 247 sound parameters (presetManager.c preset_saveDrumsetSD).
import re
import sys
from pathlib import Path

LXR_PARAMS = 247
INIT = re.compile(r"^(init|initk|initkit|empty|in\s*k)$", re.I)


def kits_in(d):
    files = []
    for f in Path(d).rglob("*"):
        m = re.match(r"^(\d+)-(.*)\.snd$", f.name, re.I)
        if m and f.is_file():
            files.append((str(f.parent), int(m.group(1)), f))
    for _, _, f in sorted(files, key=lambda t: (t[0], t[1])):
        b = f.read_bytes()
        if len(b) < 8 + 16 or len(b) > 8 + LXR_PARAMS + 64:
            continue
        name = bytes(c if 32 <= c < 127 else 32 for c in b[:8]).decode().strip()
        if INIT.match(name) or re.search(r"-(INITK|EMPTY|IN__K)\.SND$", f.name, re.I):
            continue
        data = b[8:8 + LXR_PARAMS].ljust(LXR_PARAMS, b"\0")
        yield (name or "Kit")[:8].ljust(8), data, f


def main():
    if len(sys.argv) < 3:
        sys.exit(__doc__ or "usage: gen_factory_kits.py OUT_H DIR [DIR ...]")
    out, seen, kits = Path(sys.argv[1]), set(), []
    for d in [d for a in sys.argv[2:] for d in a.split(":") if d]:   # (ELIXIR_KITS_DIR as it is: ':' between)
        if not Path(d).is_dir():
            sys.exit(f"gen_factory_kits: no folder {d}")
        for name, data, f in kits_in(d):
            if data in seen:
                continue
            seen.add(data)
            kits.append((name, data, f))
    if not kits:
        sys.exit("gen_factory_kits: no LXR kit files (NN-NAME.SND) found")
    if len(kits) > 250:
        kits = kits[:250]
    rows = []
    for name, data, f in kits:
        b = name.encode() + data
        rows.append("    {" + ", ".join(str(x) for x in b) + "},   /* " + name.strip().replace("*/", "") + " */")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("/* generated by tools/gen_factory_kits.py from local LXR-02 kit files: NOT for redistribution */\n"
                   f"#define FACTORY_NKITS {len(kits)}u\n"
                   f"static const uint8_t FACTORY_KITS[FACTORY_NKITS][8 + {LXR_PARAMS}] = {{\n"
                   + "\n".join(rows) + "\n};\n")
    print(f"factory kits: {len(kits)} ({', '.join(k[0].strip() for k in kits[:6])} ...) -> {out}")


if __name__ == "__main__":
    main()
